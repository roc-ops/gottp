#!/usr/bin/env python3
"""Generates unicode_tables.go from Python 3.12's own str methods.

Run with Python 3.12 (Unicode 15.0.0, the version Go 1.21+ uses):

    python3.12 gen_unicode.py > unicode_tables.go

The tables hold what Go's unicode package doesn't give the way Python does:

- the character classes behind str.isalpha, isdecimal, isdigit, isnumeric,
  isspace, isprintable, islower, isupper, istitle and isidentifier, and the
  Cased and Case_Ignorable properties that title, capitalize, lower and
  swapcase use;
- the full case mappings that are not one character (upper("ß") is "SS"),
  and the case folds that differ from Python's lower.

Single-character case mappings come from Go's unicode.ToUpper, ToLower and
ToTitle; TestUnicodeTablesMatchPython checks every code point against Python.
"""

import sys

if sys.version_info[:2] != (3, 12):
    sys.exit("run with Python 3.12, whose str methods gottp follows")

MAX = 0x110000
chars = [chr(i) for i in range(MAX)]


def ranges(pred):
    out = []
    start = None
    for i in range(MAX):
        if pred(i):
            if start is None:
                start = i
        elif start is not None:
            out.append((start, i - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def surrogate(i):
    return 0xD800 <= i <= 0xDFFF


lower_p = lambda i: chars[i].islower()
upper_p = lambda i: chars[i].isupper()
# A one-character string is a title only if it is titlecase or uppercase;
# titlecase alone is the one that isn't uppercase.
title_p = lambda i: chars[i].istitle() and not chars[i].isupper()
cased_p = lambda i: lower_p(i) or upper_p(i) or title_p(i)


def case_ignorable(i):
    c = chars[i]
    if surrogate(i):
        return False
    # Python's lower maps a final capital sigma to "ς": the sigma follows a
    # cased character, skipping case-ignorable ones. A cased c is probed after
    # an uncased, non-ignorable "1"; an uncased c after a cased "a".
    if cased_p(i):
        return ("1" + c + "Σ").lower()[-1] == "σ"
    return ("a" + c + "Σ").lower()[-1] == "ς"


classes = [
    ("alpha", lambda i: chars[i].isalpha()),
    ("decimal", lambda i: chars[i].isdecimal()),
    ("digit", lambda i: chars[i].isdigit()),
    ("numeric", lambda i: chars[i].isnumeric()),
    ("space", lambda i: chars[i].isspace()),
    ("printable", lambda i: chars[i].isprintable()),
    ("lower", lower_p),
    ("upper", upper_p),
    ("title", title_p),
    ("caseIgnorable", case_ignorable),
    ("xidStart", lambda i: i != 0x5F and chars[i].isidentifier()),
    ("xidContinue", lambda i: ("a" + chars[i]).isidentifier()),
]


def goquote(s):
    return '"' + "".join("\\U%08x" % ord(ch) for ch in s) + '"'


w = sys.stdout.write
w("// Code generated by gen_unicode.py from Python %s; DO NOT EDIT.\n\n" % sys.version.split()[0])
w("package pymethod\n\n")
for name, pred in classes:
    rs = ranges(lambda i: not surrogate(i) and pred(i))
    w("var %sTable = runeRanges{\n" % name)
    for lo, hi in rs:
        w("\t{0x%04X, 0x%04X},\n" % (lo, hi))
    w("}\n\n")

maps = [
    ("upperFull", lambda c: c.upper()),
    ("lowerFull", lambda c: c.lower()),
    ("titleFull", lambda c: c.title()),
]
for name, fn in maps:
    w("var %sMap = map[rune]string{\n" % name)
    for i in range(MAX):
        if surrogate(i):
            continue
        m = fn(chars[i])
        if len(m) != 1:
            w("\t0x%04X: %s,\n" % (i, goquote(m)))
    w("}\n\n")

w("// foldMap holds the case folds that differ from Python's lower.\n")
w("var foldMap = map[rune]string{\n")
for i in range(MAX):
    if surrogate(i):
        continue
    c = chars[i]
    # lower of a lone capital sigma is "σ", which is also its fold.
    if c.casefold() != c.lower():
        w("\t0x%04X: %s,\n" % (i, goquote(c.casefold())))
w("}\n")
